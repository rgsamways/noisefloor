// Reads every content/*.md file, validates it, and writes
// src/generated-articles.ts as a plain typed array — runs as a prebuild
// step (package.json's "build" script), before tsc compiles src/. Node
// can't execute src/schema.ts directly at this point (not compiled yet),
// so the shape below is a deliberate, minimal duplicate of that schema —
// keep the two in sync if either changes. See
// openspec/changes/knowledge-base design.md.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import matter from "gray-matter";
import { z } from "zod";

const ArticleSchema = z.object({
  id: z.string(),
  slug: z.string().regex(/^[a-z0-9]+(-[a-z0-9]+)*$/, "slug must be URL-safe (lowercase, hyphen-separated)"),
  title: z.string(),
  summary: z.string(),
  body: z.string(),
  relatedFields: z.array(z.string()).optional(),
});

const rootDir = path.dirname(fileURLToPath(import.meta.url));
const contentDir = path.join(rootDir, "..", "content");
const outFile = path.join(rootDir, "..", "src", "generated-articles.ts");

const files = readdirSync(contentDir).filter((f) => f.endsWith(".md"));

const articles = files.map((file) => {
  const raw = readFileSync(path.join(contentDir, file), "utf-8");
  const { data, content } = matter(raw);
  const parsed = ArticleSchema.safeParse({ ...data, body: content.trim() });
  if (!parsed.success) {
    console.error(`KB content build failed: ${file}\n${parsed.error.message}`);
    process.exit(1);
  }
  return parsed.data;
});

const seen = new Set();
for (const article of articles) {
  if (seen.has(article.slug)) {
    console.error(`KB content build failed: duplicate slug "${article.slug}"`);
    process.exit(1);
  }
  seen.add(article.slug);
}

const header = `// GENERATED by scripts/generate-articles.mjs — do not edit by hand.\nimport type { KbArticle } from "./schema.js";\n\nexport const articles: KbArticle[] = `;
writeFileSync(outFile, header + JSON.stringify(articles, null, 2) + ";\n");
console.log(`Generated ${articles.length} KB article(s) -> ${path.relative(process.cwd(), outFile)}`);
